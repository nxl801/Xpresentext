import Foundation

private actor SyntheticResponseCapture {
    struct Response: Codable, Sendable {
        let purpose: String
        var content: String
    }

    private(set) var responses: [Response] = []

    func begin(_ purpose: String) -> Int {
        let index = responses.count
        responses.append(Response(purpose: purpose, content: ""))
        return index
    }

    func append(_ content: String, to index: Int) {
        let remaining = max(0, 64_000 - responses[index].content.utf8.count)
        responses[index].content += String(decoding: content.utf8.prefix(remaining), as: UTF8.self)
    }
}

private struct SyntheticCaptureModel: QAModel {
    let model: any QAModel
    let capture: SyntheticResponseCapture
    var answerTimeout: Duration { model.answerTimeout }

    func stream(_ request: QAModelRequest) -> AsyncThrowingStream<String, Error> {
        AsyncThrowingStream { continuation in
            let task = Task {
                let purpose = request.purpose == .translateQuestion ? "translation" : "answer"
                let index = await capture.begin(purpose)
                do {
                    for try await chunk in model.stream(request) {
                        try Task.checkCancellation()
                        await capture.append(chunk, to: index)
                        continuation.yield(chunk)
                    }
                    continuation.finish()
                } catch {
                    continuation.finish(throwing: error)
                }
            }
            continuation.onTermination = { _ in task.cancel() }
        }
    }
}

extension CompanionQATests {
    private struct CapturedSyntheticCase: Codable {
        struct Citation: Codable {
            let page: Int
            let kind: QACitation.Kind
            let excerpt: String
        }

        let name: String
        let status: String
        let acceptedShortAnswer: String?
        let acceptedCitations: [Citation]?
        let responses: [SyntheticResponseCapture.Response]
    }

    private static let diagnosticQuestions = [
        (name: "draft-only-claim", question: "Did the Orchid trial cut standby power by 20%?", page: 4),
        (name: "chinese-cross-page", question: "Cedar logger 用的是什么校验方法？", page: 11)
    ]

    /// The questions and all source material are generated by this test suite.
    /// Only the model's response text is written. No requests or headers are captured.
    @MainActor
    static func captureLiveQuestionFailures(output: URL, model: any QAModel) async throws {
        var samples: [CapturedSyntheticCase] = []
        for test in diagnosticQuestions {
            let capture = SyntheticResponseCapture()
            let service = CompanionQAService(model: SyntheticCaptureModel(model: model, capture: capture))
            let session = CompanionQASession(service: service)
            session.setDeck(deck())
            session.submit(test.question, currentPageIndex: test.page)
            let deadline = ContinuousClock.now.advanced(by: model.answerTimeout + .seconds(2))
            while session.state == .answering, ContinuousClock.now < deadline {
                try await Task.sleep(for: .milliseconds(16))
            }
            let status: String
            switch session.state {
            case .completed: status = "complete"
            case .failed(let failure): status = failure.localizedDescription
            case .answering, .idle: status = "incomplete"
            }
            session.cancel()
            samples.append(CapturedSyntheticCase(
                name: test.name, status: status, acceptedShortAnswer: session.answer.shortAnswer,
                acceptedCitations: session.answer.shortAnswerPoint?.citations.map {
                    CapturedSyntheticCase.Citation(page: $0.pageNumber, kind: $0.kind, excerpt: $0.excerpt)
                },
                responses: await capture.responses
            ))
        }
        try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        try encoder.encode(samples).write(
            to: output.appendingPathComponent("synthetic-question-responses.json"), options: .atomic
        )
    }

    static func replaySyntheticCapture(_ captureFile: URL) async throws {
        let captures = try JSONDecoder().decode([CapturedSyntheticCase].self, from: Data(contentsOf: captureFile))
        try expect(captures.map(\.name) == diagnosticQuestions.map(\.name), "Unexpected synthetic capture cases")
        var passes = 0
        for (captured, test) in zip(captures, diagnosticQuestions) {
            let model = RecordedModel { request, continuation in
                let purpose = request.purpose == .translateQuestion ? "translation" : "answer"
                defer { continuation.finish() }
                guard let response = captured.responses.first(where: { $0.purpose == purpose })?.content else { return }
                var start = response.startIndex
                while start < response.endIndex {
                    let end = response.index(start, offsetBy: 17, limitedBy: response.endIndex) ?? response.endIndex
                    continuation.yield(String(response[start..<end]))
                    start = end
                }
            }
            do {
                var short: QAAnswerPoint?
                for try await update in CompanionQAService(model: model).streamAnswer(
                    test.question, index: QADeckIndex(deck()), currentPageIndex: test.page, previous: nil
                ) {
                    if case .shortAnswer(let point) = update { short = point }
                }
                let passed: Bool
                if test.name == "draft-only-claim" {
                    passed = short?.kind == .missingEvidence && short?.citations.isEmpty == true
                        && short.map { QASearchText.permitsNumbers(in: $0.text, from: []) } == true
                } else {
                    passed = short?.kind == .grounded && short?.citations.map(\.pageNumber) == [4]
                        && short?.citations.first?.kind == .speakerNotes
                        && short?.text.lowercased().contains("rolling checksum") == true
                }
                if passed { passes += 1 }
                print("\(test.name): \(passed ? "PASS" : "FAIL") \(short?.text ?? "<no answer>") \(short?.citations.map(\.pageNumber) ?? [])")
            } catch {
                print("\(test.name): FAIL \(error.localizedDescription)")
            }
        }
        if passes != diagnosticQuestions.count { exit(1) }
    }
}
